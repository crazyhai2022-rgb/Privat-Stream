#!/usr/bin/env bash
# viralX — one-command setup for a fresh Ubuntu 22.04/24.04 VPS
# (Hostinger VPS, DigitalOcean, Contabo, Oracle Cloud, AWS Lightsail … any of them).
#
# Run as root on the server:
#   bash <(curl -fsSL https://raw.githubusercontent.com/crazyhai2022-rgb/Privat-Stream/main/deploy/vps-setup.sh)
#
# Or, if you already cloned the repo:
#   sudo bash deploy/vps-setup.sh
#
# It installs Docker, writes a .env with generated secrets, starts the app and
# PostgreSQL, and prints the URL plus your admin credentials.

set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/crazyhai2022-rgb/Privat-Stream.git}"
APP_DIR="${APP_DIR:-/opt/viralx}"
APP_PORT="${APP_PORT:-4000}"

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
info() { printf '  %s\n' "$*"; }
die()  { printf '\033[31mError: %s\033[0m\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "Run this with sudo or as root."
command -v apt-get >/dev/null || die "This script expects Ubuntu or Debian."

bold "1/6  Installing packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq ca-certificates curl git ufw >/dev/null

if ! command -v docker >/dev/null; then
  info "Installing Docker…"
  curl -fsSL https://get.docker.com | sh >/dev/null
else
  info "Docker already installed."
fi
docker compose version >/dev/null 2>&1 || die "Docker Compose plugin is missing."

bold "2/6  Fetching the code into $APP_DIR"
if [ -d "$APP_DIR/.git" ]; then
  git -C "$APP_DIR" pull --ff-only
elif [ -f "$(dirname "$0")/../docker-compose.yml" ]; then
  SRC="$(cd "$(dirname "$0")/.." && pwd)"
  [ "$SRC" = "$APP_DIR" ] || { mkdir -p "$APP_DIR"; cp -r "$SRC/." "$APP_DIR/"; }
else
  git clone --depth 1 "$REPO_URL" "$APP_DIR"
fi
cd "$APP_DIR"

bold "3/6  Writing configuration"
ENV_FILE="server/.env"
if [ -f "$ENV_FILE" ]; then
  info "server/.env already exists — keeping it."
else
  SERVER_IP="$(curl -fsS --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')"
  APP_SECRET="$(head -c 32 /dev/urandom | base64 | tr -d '=+/' | cut -c1-43)"
  DB_PASSWORD="$(head -c 18 /dev/urandom | base64 | tr -d '=+/' | cut -c1-24)"
  mkdir -p server
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/vps-setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
NODE_ENV=production
PORT=4000
# Point this at your domain once DNS is set, then: docker compose up -d --force-recreate app
BASE_URL=http://${SERVER_IP}:${APP_PORT}
APP_SECRET=${APP_SECRET}
TRUST_PROXY=false

# Files are stored on this server's disk (docker volume "media").
# For several servers or a CDN, switch to S3_* and set STORAGE_DRIVER=s3.
STORAGE_DRIVER=local

# Verification and password-reset emails need SMTP. Until you fill this in,
# the links are printed in the container logs: docker compose logs -f app
SMTP_HOST=
SMTP_PORT=587
SMTP_SECURE=false
SMTP_USER=
SMTP_PASS=
MAIL_FROM="viralX <no-reply@example.com>"

PLAYBACK_FORMAT=mp4
EOF
  chmod 600 "$ENV_FILE"
  echo "POSTGRES_PASSWORD=${DB_PASSWORD}" > .env
  chmod 600 .env
  info "Wrote server/.env with a generated APP_SECRET."
fi

bold "4/6  Opening the firewall"
if ufw status >/dev/null 2>&1; then
  ufw allow OpenSSH >/dev/null 2>&1 || true
  ufw allow "${APP_PORT}/tcp" >/dev/null 2>&1 || true
  ufw allow 80/tcp >/dev/null 2>&1 || true
  ufw allow 443/tcp >/dev/null 2>&1 || true
  yes | ufw enable >/dev/null 2>&1 || true
  info "Ports 22, 80, 443 and ${APP_PORT} are open."
fi

bold "5/6  Building and starting (this takes a few minutes the first time)"
docker compose up -d --build

printf '  waiting for the app to become healthy'
for i in $(seq 1 60); do
  if curl -fsS "http://127.0.0.1:${APP_PORT}/healthz" >/dev/null 2>&1; then printf ' ok\n'; break; fi
  printf '.'; sleep 3
  [ "$i" -eq 60 ] && { printf '\n'; docker compose logs --tail 40 app; die "The app did not start. The logs above show why."; }
done

bold "6/6  Creating your administrator"
ADMIN_EMAIL="${ADMIN_EMAIL:-}"
if [ -z "$ADMIN_EMAIL" ]; then
  read -rp "  Admin email: " ADMIN_EMAIL </dev/tty || true
fi
if [ -n "$ADMIN_EMAIL" ]; then
  docker compose exec -T app node src/scripts/create-admin.js --email "$ADMIN_EMAIL" --name "${ADMIN_NAME:-Administrator}" --generate \
    || info "Could not create the admin automatically. Run it yourself with the command below."
else
  info "Skipped. Create one with:"
  info "  cd $APP_DIR && docker compose exec app node src/scripts/create-admin.js --email you@example.com --name 'Your Name' --generate"
fi

BASE="$(grep -E '^BASE_URL=' "$ENV_FILE" | cut -d= -f2-)"
echo
bold "viralX is running"
info "Site:  ${BASE}"
info "Admin: ${BASE}/admin"
echo
info "Useful commands (run them inside $APP_DIR):"
info "  docker compose logs -f app        # watch the logs"
info "  docker compose restart app        # restart"
info "  git pull && docker compose up -d --build   # deploy the latest code"
echo
info "Next: point a domain at this server, then put nginx or Caddy in front for"
info "HTTPS and update BASE_URL in server/.env — see docs/DEPLOYMENT.md."
